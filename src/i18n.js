let current = 'ja';

export function detectLang(navLangs) {
  const list = navLangs || (typeof navigator !== 'undefined' ? navigator.languages || [navigator.language] : []);
  for (const l of list) {
    const code = String(l || '').toLowerCase().slice(0, 2);
    if (STR[code]) return code;
  }
  return 'en';
}

export function setLang(code) {
  current = STR[code] ? code : 'en';
  if (typeof document !== 'undefined') {
    document.documentElement.lang = current === 'zh' ? 'zh-Hans' : current;
    applyI18n(document);
  }
  return current;
}

export function getLang() { return current; }

export function t(key, vars = {}) {
  const s = (STR[current] && STR[current][key]) ?? STR.en[key] ?? key;
  return s.replace(/\{(\w+)\}/g, (_, k) => (vars[k] !== undefined ? vars[k] : `{${k}}`));
}

export function applyI18n(root) {
  root.querySelectorAll('[data-i18n]').forEach((el) => { el.textContent = t(el.dataset.i18n); });
}

export const STRINGS = STR;
